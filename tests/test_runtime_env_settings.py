def test_configuration_route_accepts_webhook_secret_without_config_payload_storage():
    from services.routes import update_config_route

    signature = inspect.signature(update_config_route)
    route_source = inspect.getsource(update_config_route)

    assert "webhook_secret" in signature.parameters
    assert "save_runtime_secret" in route_source
    assert 'app_settings["WEBHOOK_SECRET"]' not in route_source


